# Ninth program: integer division, remainder (modulo) and exponentiation.

a = int(input('Enter the value of the first number: '))
b = int(input('Enter the value of the second number: '))

integer_division = a // b
remainder = a % b
power = a ** b

print(f'Integer division: {integer_division}')
print(f'Remainder: {remainder}')
print(f'Power: {power}')
